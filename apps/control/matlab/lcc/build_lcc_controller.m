function model = build_lcc_controller()
%BUILD_LCC_CONTROLLER Create LCC_Controller.slx (the lateral MPC that is turned into C++).
%   build_lcc_controller() rebuilds LCC_Controller.slx in this folder. Root I/O follows the
%   node contract (9 inputs, 3 outputs, README.md "입출력 계약"). Everything sits in the atomic
%   subsystem "LCC_Controller":
%     MPC_Prep   (MATLAB Function -> lcc_mpc_prep.m: model at this speed, state, previewed
%                 curvature, references, steering-rate bounds, bias observer, fallback law)
%     MPC        (Adaptive MPC Controller, mpcLcc from lcc_design_mpc.m; the plant model is
%                 replaced every step through the model bus A, B, C, D, X, U, Y, DX)
%     MPC_Post   (MATLAB Function -> lcc_mpc_post.m: wheel angle / rate command, status)
%     memory     (Unit Delay: [epsi_pred; kb; mpc_active; delta_pred; ub; u(k-1) .. u(k-nd-1)])
%   The model workspace runs lcc_controller_params(); the InitFcn puts mpcLcc in the base
%   workspace (lcc_controller_init). Fixed step 0.02 s, ERT / C++ class (lcc_codegen_config).
here = fileparts(mfilename("fullpath"));
C = lcc_controller_params();
model = 'LCC_Controller';
if bdIsLoaded(model), close_system(model, 0); end
file = fullfile(here, model + ".slx");
if isfile(file), delete(file); end
new_system(model);
load_system(model);
set_param(model, "Description", ['ETS2 truck lane centering (adaptive MPC on a kinematic truck + trailer ' ...
    'model, curvature preview). Built by build_lcc_controller.m; parameters lcc_controller_params.m.']);
hws = get_param(model, "ModelWorkspace");
hws.DataSource = "MATLAB Code";
hws.MATLABCode = strjoin([
    "% Generated by build_lcc_controller.m (edit lcc_controller_params.m / lcc_design_mpc.m)"
    "C = lcc_controller_params();"
    "lcc_controller_init();   % mpcLcc in the base workspace (the MPC block reads it there)"], newline);
hws.reload();
lcc_codegen_config(model);
set_param(model, "InitFcn", "lcc_controller_init;");

% ---------------- root I/O (contract) ----------------
ins = {"enable", "boolean", "1"; "speed_mps", "double", "1"; "lateral_error_m", "double", "1";
       "heading_error_rad", "double", "1"; "curvature_preview", "double", num2str(C.n_preview);
       "wheel_angle_rad", "double", "1"; "wheelbase_m", "double", "1";
       "trailer_connected", "boolean", "1"; "hitch_angle_rad", "double", "1"};
outs = {"wheel_angle_cmd_rad", "double"; "wheel_rate_cmd_rad_s", "double"; "status", "uint8"};
for i = 1:size(ins, 1)
    add_block("simulink/Sources/In1", model + "/" + ins{i, 1}, "Port", num2str(i), ...
        "OutDataTypeStr", ins{i, 2}, "PortDimensions", ins{i, 3}, "SampleTime", "C.Ts", ...
        "Position", [40 40+45*i 70 54+45*i]);
end
for i = 1:size(outs, 1)
    add_block("simulink/Sinks/Out1", model + "/" + outs{i, 1}, "Port", num2str(i), ...
        "OutDataTypeStr", outs{i, 2}, "Position", [900 100+60*i 930 114+60*i]);
end
sub = model + "/LCC_Controller";
add_block("simulink/Ports & Subsystems/Subsystem", sub, "Position", [400 80 620 520]);
delete_line(sub, "In1/1", "Out1/1"); delete_block(sub + "/In1"); delete_block(sub + "/Out1");
set_param(sub, "TreatAsAtomicUnit", "on");
for i = 1:size(ins, 1)
    add_block("simulink/Sources/In1", sub + "/" + ins{i, 1}, "Port", num2str(i));
    add_line(model, ins{i, 1} + "/1", "LCC_Controller/" + i);
end
for i = 1:size(outs, 1)
    add_block("simulink/Sinks/Out1", sub + "/" + outs{i, 1}, "Port", num2str(i));
    add_line(model, "LCC_Controller/" + i, outs{i, 1} + "/1");
end
build_inside(sub, C);
Simulink.BlockDiagram.arrangeSystem(sub);
save_system(model, file);
end

% =====================================================================
function build_inside(sub, C)
rt = sfroot;
mfun(sub, "MPC_Prep", strjoin([
"function [A, B, Cm, Dm, x0, md, ref, umin, umax, mv_ext, mode, fb_angle, fb_rate, obs, pred_rows, conv] = MPC_Prep(enable, v, ey, epsi, preview, delta, wheelbase, trailer, hitch, mem, C)"
"[A, B, Cm, Dm, x0, md, ref, umin, umax, mv_ext, mode, fb_angle, fb_rate, obs, pred_rows, conv] = lcc_mpc_prep(enable, v, ey, epsi, preview, delta, wheelbase, trailer, hitch, mem, C);"], newline), rt);
names = ["enable", "speed_mps", "lateral_error_m", "heading_error_rad", "curvature_preview", ...
         "wheel_angle_rad", "wheelbase_m", "trailer_connected", "hitch_angle_rad"];
for i = 1:numel(names), ln(sub, names(i) + "/1", "MPC_Prep/" + i); end

% model bus (names A, B, C, D, X, U, Y, DX are what the Adaptive MPC block expects)
add_block("simulink/Signal Routing/Bus Creator", sub + "/model_bus", "Inputs", "8");
add_block("simulink/Sources/Constant", sub + "/X0", "Value", "zeros(5+C.act.nd,1)", "SampleTime", "C.Ts", "VectorParams1D", "off");
add_block("simulink/Sources/Constant", sub + "/U0", "Value", "zeros(2,1)", "SampleTime", "C.Ts", "VectorParams1D", "off");
add_block("simulink/Sources/Constant", sub + "/Y0", "Value", "zeros(6,1)", "SampleTime", "C.Ts", "VectorParams1D", "off");
add_block("simulink/Sources/Constant", sub + "/DX0", "Value", "zeros(5+C.act.nd,1)", "SampleTime", "C.Ts", "VectorParams1D", "off");
src = ["MPC_Prep/1", "MPC_Prep/2", "MPC_Prep/3", "MPC_Prep/4", "X0/1", "U0/1", "Y0/1", "DX0/1"];
nm = ["A", "B", "C", "D", "X", "U", "Y", "DX"];
for i = 1:8
    h = add_line(sub, src(i), "model_bus/" + i, "autorouting", "smart");
    set_param(h, "Name", nm(i));
end

mpcb = sub + "/MPC";
add_block("mpclib/Adaptive MPC Controller", mpcb);
lcc_controller_init();
set_param(mpcb, "mpcobj", "mpcLcc", "state_inport", "on", "md_inport", "on", "mv_inport", "on", ...
    "umin_inport", "on", "umax_inport", "on", "return_qpstatus", "on");
% ports: 1 model 2 x[k|k] 3 ref 4 md 5 ext.mv 6 umin 7 umax
ln(sub, "model_bus/1", "MPC/1"); ln(sub, "MPC_Prep/5", "MPC/2"); ln(sub, "MPC_Prep/7", "MPC/3");
ln(sub, "MPC_Prep/6", "MPC/4"); ln(sub, "MPC_Prep/10", "MPC/5"); ln(sub, "MPC_Prep/8", "MPC/6");
ln(sub, "MPC_Prep/9", "MPC/7");

mfun(sub, "MPC_Post", strjoin([
"function [wheel_angle_cmd, wheel_rate_cmd, status, mem] = MPC_Post(mv, qp_status, mode, fb_angle, fb_rate, x0, md, obs, pred_rows, delta, conv, C)"
"[wheel_angle_cmd, wheel_rate_cmd, status, mem] = lcc_mpc_post(mv, qp_status, mode, fb_angle, fb_rate, x0, md(1), obs, pred_rows, delta, conv, C);"], newline), rt);
ln(sub, "MPC/1", "MPC_Post/1"); ln(sub, "MPC/2", "MPC_Post/2"); ln(sub, "MPC_Prep/11", "MPC_Post/3");
ln(sub, "MPC_Prep/12", "MPC_Post/4"); ln(sub, "MPC_Prep/13", "MPC_Post/5"); ln(sub, "MPC_Prep/5", "MPC_Post/6");
ln(sub, "MPC_Prep/6", "MPC_Post/7"); ln(sub, "MPC_Prep/14", "MPC_Post/8"); ln(sub, "MPC_Prep/15", "MPC_Post/9");
ln(sub, "wheel_angle_rad/1", "MPC_Post/10"); ln(sub, "MPC_Prep/16", "MPC_Post/11");
add_block("simulink/Discrete/Unit Delay", sub + "/memory", "SampleTime", "C.Ts", "InitialCondition", "zeros(C.mem_n,1)");
ln(sub, "MPC_Post/4", "memory/1"); ln(sub, "memory/1", "MPC_Prep/10");
ln(sub, "MPC_Post/1", "wheel_angle_cmd_rad/1"); ln(sub, "MPC_Post/2", "wheel_rate_cmd_rad_s/1");
ln(sub, "MPC_Post/3", "status/1");
end

function mfun(sub, name, script, rt)
path = sub + "/" + name;
add_block("simulink/User-Defined Functions/MATLAB Function", path);
ch = rt.find("-isa", "Stateflow.EMChart", "Path", char(path));
ch.Script = char(script);
d = ch.find("-isa", "Stateflow.Data", "Name", "C");
d.Scope = "Parameter";
d.Tunable = false;
% fixed sizes for the outputs the MPC block reads
end

function ln(sys, from, to)
add_line(sys, from, to, "autorouting", "smart");
end
