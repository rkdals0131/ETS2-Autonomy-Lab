function model = build_lcc_plant()
%BUILD_LCC_PLANT Create lcc_plant.slx: lateral plant of the Scania S 6x2 (+ box trailer).
%   build_lcc_plant() rebuilds lcc_plant.slx in this folder. Parameters live in the model
%   workspace (MATLAB code): P = lcc_plant_params("trailer") and LANE = lcc_lane(...).tab;
%   scenarios overwrite both (SimulationInput.setVariable(..., "Workspace", "lcc_plant")).
%
%   Root inputs : 1 wheel_angle_target (rad)  2 wheel_rate_ff (rad/s)  3 speed (m/s)
%   Root outputs: 1 lateral_error (m, left +)  2 heading_error (rad)  3 wheel_angle (rad, actual)
%                 4 hitch_angle (rad, 0 without trailer)  5 curvature_preview (61, 1/m)
%                 6 kappa_back (mean curvature at s - w/2)  7 s  8 X  9 Y  10 psi  11 psi_trailer
%                 12 yaw_rate  13 lat_accel  14 eff (applied steering)  15 u (game steering input,
%                 after the frame delay)
%                 16 kappa (lane curvature at s)
%   Subsystems:
%     SteeringActuator  node VirtualEps (50 Hz, lcc_virtual_eps.m) -> one game frame delay ->
%                       measured relative steering d(eff)/dt = a(v) u - c(v) eff -> 0.70 rad/unit
%     Vehicle           kinematic bicycle with speed-dependent wheelbase and reference-point
%                       sideslip + kinematic trailer with hitch offset (lcc_vehicle_deriv.m), in
%                       lane (Frenet) and world coordinates, ode4 5 ms
%     LaneSensor        curvature preview the node reads from its polyline (lcc_lane_sensor.m), 50 Hz
here = fileparts(mfilename("fullpath"));
P = lcc_plant_params("trailer");
model = 'lcc_plant';
if bdIsLoaded(model), close_system(model, 0); end
file = fullfile(here, model + ".slx");
if isfile(file), delete(file); end
new_system(model);
load_system(model);
set_param(model, "SolverType", "Fixed-step", "Solver", "ode4", "FixedStep", num2str(P.sim.step), ...
    "StopTime", "30", "SaveOutput", "on", "OutputSaveName", "yout", "SaveFormat", "Dataset", ...
    "SaveTime", "on", "ReturnWorkspaceOutputs", "on", "AlgebraicLoopMsg", "error", ...
    "ModelReferenceMinAlgLoopOccurrences", "on");   % only the u output feeds through
set_param(model, "Description", ['ETS2 Scania S 6x2 tag lift (+ empty box trailer), lateral plant for the LCC. ' ...
    'Built by build_lcc_plant.m; parameters lcc_plant_params.m (sources there).']);
hws = get_param(model, "ModelWorkspace");
hws.DataSource = "MATLAB Code";
hws.MATLABCode = strjoin([
    "% Generated by build_lcc_plant.m (edit lcc_plant_params.m)"
    "P = lcc_plant_params(""trailer"");"
    "LANE = lcc_lane(zeros(0, 2)).tab;   % straight lane; scenarios overwrite P and LANE"], newline);
hws.reload();
rt = sfroot;

% ---------------- root ports ----------------
ins = ["wheel_angle_target", "wheel_rate_ff", "speed"];
for i = 1:numel(ins)
    add_block("simulink/Sources/In1", model + "/" + ins(i), "Port", num2str(i), "Position", [30 60+70*i 60 74+70*i]);
end
outs = ["lateral_error", "heading_error", "wheel_angle", "hitch_angle", "curvature_preview", "kappa_back", ...
        "s", "X", "Y", "psi", "psi_trailer", "yaw_rate", "lat_accel", "eff", "u", "kappa"];
for i = 1:numel(outs)
    add_block("simulink/Sinks/Out1", model + "/" + outs(i), "Port", num2str(i), "Position", [1100 30+40*i 1130 44+40*i]);
end

% ---------------- steering actuator ----------------
sa = model + "/SteeringActuator";
subsys(sa, ["target", "rate", "speed"], ["eff", "delta", "u"]);
mfun(sa, "VirtualEps", strjoin([
"function u = VirtualEps(target, rate, eff, speed, P)"
"% node inner loop (virtual_eps.hpp), 50 Hz"
"u = lcc_virtual_eps(target, rate, eff, speed, P.eps, P.geo.wheel_angle_per_unit);"], newline), rt, ["P"]);
set_param(sa + "/VirtualEps", "SystemSampleTime", "P.sim.ctrl_dt");
add_block("simulink/Continuous/Transport Delay", sa + "/game_frame", "DelayTime", "P.steer.delay", "InitialOutput", "0");
mfun(sa, "SteeringRack", strjoin([
"function deff = SteeringRack(u, eff, speed, P)"
"% measured relative steering: d(eff)/dt = a(v)*u - c(v)*eff (docs/31 조향 계통)"
"kmh = abs(speed) * 3.6;"
"a = interp1(P.steer.kmh, P.steer.a, min(kmh, P.steer.kmh(end)));"
"c = P.steer.c_scale * interp1(P.steer.kmh, P.steer.c, min(kmh, P.steer.kmh(end)));"
"deff = a * u - c * eff;"], newline), rt, ["P"]);
add_block("simulink/Continuous/Integrator", sa + "/eff_int", "InitialCondition", "P.init.eff", ...
    "LimitOutput", "on", "UpperSaturationLimit", "P.geo.eff_max", "LowerSaturationLimit", "-P.geo.eff_max");
add_block("simulink/Math Operations/Gain", sa + "/angle_per_unit", "Gain", "P.geo.wheel_angle_per_unit");
ln(sa, "target/1", "VirtualEps/1"); ln(sa, "rate/1", "VirtualEps/2"); ln(sa, "eff_int/1", "VirtualEps/3");
ln(sa, "speed/1", "VirtualEps/4");
ln(sa, "VirtualEps/1", "game_frame/1"); ln(sa, "game_frame/1", "SteeringRack/1");
ln(sa, "eff_int/1", "SteeringRack/2"); ln(sa, "speed/1", "SteeringRack/3");
ln(sa, "SteeringRack/1", "eff_int/1");
ln(sa, "eff_int/1", "angle_per_unit/1"); ln(sa, "eff_int/1", "eff/1"); ln(sa, "angle_per_unit/1", "delta/1");
ln(sa, "game_frame/1", "u/1");          % the input the game applies (no direct feedthrough)
Simulink.BlockDiagram.arrangeSystem(sa);

% ---------------- vehicle ----------------
vh = model + "/Vehicle";
subsys(vh, ["delta", "speed"], ["x", "yaw_rate", "lat_accel", "kappa"]);
mfun(vh, "Kinematics", strjoin([
"function [dx, r, ay, kappa] = Kinematics(x, delta, speed, t, P, LANE)"
"% x = [s; ey; epsi; hitch; X; Y; psi] (lcc_vehicle_deriv.m); slow yaw-rate wander P.dist"
"[~, kappa] = lcc_lane_lookup(LANE, x(1));"
"d = sum(P.dist.amp * sin(2*pi*P.dist.freq*t + P.dist.phase));"
"[dx, r, ay] = lcc_vehicle_deriv(x, delta, speed, P.geo.L, kappa, P, d);"], newline), rt, ["P", "LANE"]);
add_block("simulink/Sources/Clock", vh + "/clock");
add_block("simulink/Continuous/Integrator", vh + "/state", "InitialCondition", ...
    "[P.init.s; P.init.ey; P.init.epsi; P.init.hitch; P.init.X; P.init.Y; P.init.psi]");
ln(vh, "state/1", "Kinematics/1"); ln(vh, "delta/1", "Kinematics/2"); ln(vh, "speed/1", "Kinematics/3");
ln(vh, "clock/1", "Kinematics/4");
ln(vh, "Kinematics/1", "state/1");
ln(vh, "state/1", "x/1"); ln(vh, "Kinematics/2", "yaw_rate/1"); ln(vh, "Kinematics/3", "lat_accel/1");
ln(vh, "Kinematics/4", "kappa/1");
Simulink.BlockDiagram.arrangeSystem(vh);

% ---------------- lane sensor ----------------
ls = model + "/LaneSensor";
subsys(ls, "s", ["curvature_preview", "kappa_back"]);
mfun(ls, "Preview", strjoin([
"function [preview, kappa_back] = Preview(s, P, LANE)"
"% node: LanePath::curvature(s + i*ds, window), i = 0..60"
"[preview, kappa_back] = lcc_lane_sensor(s, LANE, P.lane);"], newline), rt, ["P", "LANE"]);
set_param(ls + "/Preview", "SystemSampleTime", "P.sim.ctrl_dt");
ln(ls, "s/1", "Preview/1"); ln(ls, "Preview/1", "curvature_preview/1"); ln(ls, "Preview/2", "kappa_back/1");
Simulink.BlockDiagram.arrangeSystem(ls);

% ---------------- wiring ----------------
% speed through a 5 ms Memory: no direct feedthrough from any input to an output, so the
% closed loop's Model block does not form an algebraic loop
add_block("simulink/Discrete/Memory", model + "/speed_mem", "InitialCondition", "P.init.speed");
ln(model, "speed/1", "speed_mem/1");
ln(model, "wheel_angle_target/1", "SteeringActuator/1"); ln(model, "wheel_rate_ff/1", "SteeringActuator/2");
ln(model, "speed_mem/1", "SteeringActuator/3");
ln(model, "SteeringActuator/2", "Vehicle/1"); ln(model, "speed_mem/1", "Vehicle/2");
add_block("simulink/Signal Routing/Demux", model + "/x_demux", "Outputs", "7");
ln(model, "Vehicle/1", "x_demux/1");
ln(model, "x_demux/1", "LaneSensor/1");
add_block("simulink/Math Operations/Gain", model + "/trailer_flag", "Gain", "double(P.trailer_connected)");
add_block("simulink/Math Operations/Sum", model + "/psi_t", "Inputs", "+-");
ln(model, "x_demux/4", "trailer_flag/1");
ln(model, "x_demux/7", "psi_t/1"); ln(model, "x_demux/4", "psi_t/2");
ln(model, "x_demux/2", "lateral_error/1"); ln(model, "x_demux/3", "heading_error/1");
ln(model, "SteeringActuator/2", "wheel_angle/1"); ln(model, "trailer_flag/1", "hitch_angle/1");
ln(model, "LaneSensor/1", "curvature_preview/1"); ln(model, "LaneSensor/2", "kappa_back/1");
ln(model, "x_demux/1", "s/1"); ln(model, "x_demux/5", "X/1"); ln(model, "x_demux/6", "Y/1");
ln(model, "x_demux/7", "psi/1"); ln(model, "psi_t/1", "psi_trailer/1");
ln(model, "Vehicle/2", "yaw_rate/1"); ln(model, "Vehicle/3", "lat_accel/1");
ln(model, "SteeringActuator/1", "eff/1"); ln(model, "SteeringActuator/3", "u/1");
ln(model, "Vehicle/4", "kappa/1");
Simulink.BlockDiagram.arrangeSystem(model);
save_system(model, file);
end

% =====================================================================
function subsys(path, ins, outs)
add_block("simulink/Ports & Subsystems/Subsystem", path);
delete_line(path, "In1/1", "Out1/1"); delete_block(path + "/In1"); delete_block(path + "/Out1");
for i = 1:numel(ins)
    add_block("simulink/Sources/In1", path + "/" + ins(i), "Port", num2str(i));
end
for i = 1:numel(outs)
    add_block("simulink/Sinks/Out1", path + "/" + outs(i), "Port", num2str(i));
end
end

function mfun(sys, name, script, rt, params)
path = sys + "/" + name;
add_block("simulink/User-Defined Functions/MATLAB Function", path);
ch = rt.find("-isa", "Stateflow.EMChart", "Path", char(path));
ch.Script = char(script);
for p = params
    d = ch.find("-isa", "Stateflow.Data", "Name", char(p));
    d.Scope = "Parameter";
    d.Tunable = true;
end
end

function ln(sys, from, to)
add_line(sys, from, to, "autorouting", "smart");
end
