function model = build_lcc_closed_loop()
%BUILD_LCC_CLOSED_LOOP Create lcc_closed_loop.slx: lateral controller + lcc_plant.
%   build_lcc_closed_loop() rebuilds lcc_closed_loop.slx in this folder. The plant
%   (lcc_plant.slx, ode4 5 ms) is a Model block; the lateral controller is a Variant Subsystem
%   "Lateral" with two choices selected by the base-workspace variable LCC_CTRL:
%     LCC_CTRL == 1  Baseline  lateral_controller.hpp ported to MATLAB (lcc_baseline.m)
%     LCC_CTRL == 2  MPC       LCC_Controller.slx as a Model block (set its SimulationMode to
%                              "Software-in-the-loop (SIL)" to run the generated code)
%   Both feed the plant's SteeringActuator (node VirtualEps) with a wheel angle target and
%   rate at 50 Hz. Scenario values sit in the model workspace (SCN: speed, wheelbase given to
%   the controller, trailer flag, baseline settings), the plant's in its own (P, LANE).
%   Outputs (Dataset yout): the 16 plant outputs, wheel_angle_cmd, wheel_rate_cmd, status and
%   ctrl_in (the 69 controller inputs as doubles, for the SIL comparison).
here = fileparts(mfilename("fullpath"));
model = 'lcc_closed_loop';
if bdIsLoaded(model), close_system(model, 0); end
for m = ["lcc_plant", "LCC_Controller"]
    if bdIsLoaded(m), close_system(m, 0); end
end
file = fullfile(here, model + ".slx");
if isfile(file), delete(file); end
P = lcc_plant_params("trailer");
new_system(model);
load_system(model);
set_param(model, "SolverType", "Fixed-step", "Solver", "ode4", "FixedStep", num2str(P.sim.step), "StopTime", "60", ...
    "SaveOutput", "on", "OutputSaveName", "yout", "SaveFormat", "Dataset", "SaveTime", "on", ...
    "ReturnWorkspaceOutputs", "on", "AutoInsertRateTranBlk", "on", "SignalLogging", "off");
set_param(model, "Description", ['LCC closed loop: lateral controller (variant LCC_CTRL: 1 baseline, 2 MPC) + ' ...
    'lcc_plant. Built by build_lcc_closed_loop.m.']);
hws = get_param(model, "ModelWorkspace");
hws.DataSource = "MATLAB Code";
hws.MATLABCode = strjoin([
    "% Generated by build_lcc_closed_loop.m; run_lcc_scenarios.m overwrites SCN"
    "SCN = struct('speed', 60/3.6, 'wheelbase', 3.158, 'trailer', true, 'enable', true, ..."
    "    'base', struct('lookahead_m', 6, 'lookahead_time_s', 0.7, 'window', 6));"], newline);
hws.reload();

% ---------------- plant ----------------
add_block("simulink/Ports & Subsystems/Model", model + "/Plant", "ModelName", "lcc_plant", ...
    "Position", [900 100 1100 700]);
% ---------------- scenario constants ----------------
add_block("simulink/Sources/Constant", model + "/speed", "Value", "SCN.speed");
add_block("simulink/Sources/Constant", model + "/enable", "Value", "SCN.enable", "OutDataTypeStr", "boolean", "SampleTime", "0.02");
add_block("simulink/Sources/Constant", model + "/wheelbase", "Value", "SCN.wheelbase", "SampleTime", "0.02");
add_block("simulink/Sources/Constant", model + "/trailer", "Value", "SCN.trailer", "OutDataTypeStr", "boolean", "SampleTime", "0.02");

% ---------------- lateral controller variants ----------------
vs = model + "/Lateral";
add_block("simulink/Ports & Subsystems/Variant Subsystem", vs, "Position", [500 100 700 600]);
for b = string(find_system(vs, "SearchDepth", 1, "MatchFilter", @Simulink.match.allVariants)).'
    if b ~= vs, delete_block(b); end
end
ins = ["enable", "speed", "ey", "epsi", "preview", "delta", "wheelbase", "trailer", "hitch", "kappa_back"];
outs = ["wheel_angle_cmd", "wheel_rate_cmd", "status"];
for i = 1:numel(ins), add_block("simulink/Sources/In1", vs + "/" + ins(i), "Port", num2str(i)); end
for i = 1:numel(outs), add_block("simulink/Sinks/Out1", vs + "/" + outs(i), "Port", num2str(i)); end
% choice 1: baseline
cb = vs + "/Baseline";
add_block("simulink/Ports & Subsystems/Subsystem", cb);
delete_line(cb, "In1/1", "Out1/1"); delete_block(cb + "/In1"); delete_block(cb + "/Out1");
for i = 1:numel(ins), add_block("simulink/Sources/In1", cb + "/" + ins(i), "Port", num2str(i)); end
for i = 1:numel(outs), add_block("simulink/Sinks/Out1", cb + "/" + outs(i), "Port", num2str(i)); end
add_block("simulink/User-Defined Functions/MATLAB Function", cb + "/LateralController");
rt = sfroot;
ch = rt.find("-isa", "Stateflow.EMChart", "Path", char(cb + "/LateralController"));
ch.Script = char(strjoin([
"function [wheel_angle, wheel_rate, status] = LateralController(enable, ey, epsi, v, wheelbase, preview, kappa_back, SCN)"
"% lateral_controller.hpp (LateralController::update), 50 Hz"
"[wheel_angle, wheel_rate] = lcc_baseline(ey, epsi, v, wheelbase, preview, kappa_back, SCN.base);"
"status = uint8(enable);"], newline));
d = ch.find("-isa", "Stateflow.Data", "Name", "SCN"); d.Scope = "Parameter"; d.Tunable = true;
set_param(cb + "/LateralController", "SystemSampleTime", "0.02");
ln(cb, "enable/1", "LateralController/1"); ln(cb, "ey/1", "LateralController/2"); ln(cb, "epsi/1", "LateralController/3");
ln(cb, "speed/1", "LateralController/4"); ln(cb, "wheelbase/1", "LateralController/5");
ln(cb, "preview/1", "LateralController/6"); ln(cb, "kappa_back/1", "LateralController/7");
for i = 1:3, ln(cb, "LateralController/" + i, outs(i) + "/1"); end
for t = ["delta", "trailer", "hitch"]
    add_block("simulink/Sinks/Terminator", cb + "/unused_" + t); ln(cb, t + "/1", "unused_" + t + "/1");
end
set_param(cb, "VariantControl", "LCC_CTRL == 1");
% choice 2: MPC (generated-code model)
cm = vs + "/MPC";
add_block("simulink/Ports & Subsystems/Subsystem", cm);
delete_line(cm, "In1/1", "Out1/1"); delete_block(cm + "/In1"); delete_block(cm + "/Out1");
for i = 1:numel(ins), add_block("simulink/Sources/In1", cm + "/" + ins(i), "Port", num2str(i)); end
for i = 1:numel(outs), add_block("simulink/Sinks/Out1", cm + "/" + outs(i), "Port", num2str(i)); end
add_block("simulink/Ports & Subsystems/Model", cm + "/Controller", "ModelName", "LCC_Controller");
for i = 1:9, ln(cm, ins(i) + "/1", "Controller/" + i); end
for i = 1:3, ln(cm, "Controller/" + i, outs(i) + "/1"); end
for i = 4:6   % predicted trajectory (predicted_offset_m, predicted_heading_rad, predicted_dt_s): not used here
    add_block("simulink/Sinks/Terminator", cm + "/unused_pred" + i); ln(cm, "Controller/" + i, "unused_pred" + i + "/1");
end
add_block("simulink/Sinks/Terminator", cm + "/unused_kappa_back"); ln(cm, "kappa_back/1", "unused_kappa_back/1");
set_param(cm, "VariantControl", "LCC_CTRL == 2");
set_param(vs, "VariantActivationTime", "update diagram");

% ---------------- wiring ----------------
% plant outputs: 1 ey 2 epsi 3 delta 4 hitch 5 preview 6 kappa_back 7 s 8 X 9 Y 10 psi 11 psi_t
%                12 r 13 ay 14 eff 15 u 16 kappa
ln(model, "enable/1", "Lateral/1"); ln(model, "speed/1", "Lateral/2");
ln(model, "Plant/1", "Lateral/3"); ln(model, "Plant/2", "Lateral/4"); ln(model, "Plant/5", "Lateral/5");
ln(model, "Plant/3", "Lateral/6"); ln(model, "wheelbase/1", "Lateral/7"); ln(model, "trailer/1", "Lateral/8");
ln(model, "Plant/4", "Lateral/9"); ln(model, "Plant/6", "Lateral/10");
ln(model, "Lateral/1", "Plant/1"); ln(model, "Lateral/2", "Plant/2"); ln(model, "speed/1", "Plant/3");

% ---------------- logged outputs ----------------
pnames = ["ey", "epsi", "delta", "hitch", "preview", "kappa_back", "s", "X", "Y", "psi", "psi_t", ...
          "r", "ay", "eff", "u", "kappa"];
k = 0;
for i = 1:numel(pnames)
    k = k + 1;
    add_block("simulink/Sinks/Out1", model + "/" + pnames(i) + "_out", "Port", num2str(k));
    ln(model, "Plant/" + i, pnames(i) + "_out/1");
end
add_block("simulink/Signal Attributes/Data Type Conversion", model + "/status_d", "OutDataTypeStr", "double");
ln(model, "Lateral/3", "status_d/1");
cout = ["wheel_angle_cmd", "Lateral/1"; "wheel_rate_cmd", "Lateral/2"; "status", "status_d/1"];
for i = 1:size(cout, 1)
    k = k + 1;
    add_block("simulink/Sinks/Out1", model + "/" + cout(i, 1) + "_out", "Port", num2str(k));
    ln(model, cout(i, 2), cout(i, 1) + "_out/1");
end
% the controller inputs as doubles (contract order) for the SIL comparison
add_block("simulink/Signal Routing/Mux", model + "/ctrl_in_mux", "Inputs", "9");
cin = ["enable/1", "speed/1", "Plant/1", "Plant/2", "Plant/5", "Plant/3", "wheelbase/1", "trailer/1", "Plant/4"];
for i = 1:numel(cin)
    c = sprintf("cin_%d", i);
    add_block("simulink/Signal Attributes/Data Type Conversion", model + "/" + c, "OutDataTypeStr", "double");
    ln(model, cin(i), c + "/1"); ln(model, c + "/1", sprintf("ctrl_in_mux/%d", i));
end
add_block("simulink/Signal Attributes/Rate Transition", model + "/ctrl_in_rt", "OutPortSampleTime", "0.02");
ln(model, "ctrl_in_mux/1", "ctrl_in_rt/1");
k = k + 1;
add_block("simulink/Sinks/Out1", model + "/ctrl_in_out", "Port", num2str(k));
ln(model, "ctrl_in_rt/1", "ctrl_in_out/1");
Simulink.BlockDiagram.arrangeSystem(model);
save_system(model, file);
end

function ln(sys, from, to)
add_line(sys, from, to, "autorouting", "smart");
end
