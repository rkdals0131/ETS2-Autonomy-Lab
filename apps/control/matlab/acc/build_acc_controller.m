function model = build_acc_controller()
%BUILD_ACC_CONTROLLER Create ACC_Controller.slx (the controller that is turned into C++).
%   build_acc_controller() rebuilds ACC_Controller.slx in this folder. Root I/O follows the
%   ROS 2 contract (12 inputs, 6 outputs). Everything sits in the atomic subsystem
%   "ACC_Controller":
%     InputConditioning (MATLAB Function -> acc_condition.m)
%     ModeLogic         (Stateflow: OFF, CRUISE, FOLLOW, STOP, HOLD, GO, EMERGENCY)
%     MPC_Prep          (MATLAB Function -> acc_mpc_prep.m: state, references, bounds, weights)
%     MPC               (Multiple MPC Controllers: mpcComfort / mpcEmergency, acc_design_mpc.m)
%     MPC_Post          (MATLAB Function: mean of the predicted request over 3 s)
%     Allocator         (MATLAB Function -> acc_allocate.m: throttle, brake, retarder step)
%   The model workspace runs acc_controller_params() and acc_design_mpc(); the chart
%   parameters MODE_* / FOL_* are generated from C. Fixed step 0.05 s, ERT / C++ class
%   settings are applied by acc_codegen_config (also used by generate_acc_code.m).
here = fileparts(mfilename("fullpath"));
C = acc_controller_params();
model = 'ACC_Controller';
if bdIsLoaded(model), close_system(model, 0); end
file = fullfile(here, model + ".slx");
if isfile(file), delete(file); end
new_system(model);
load_system(model);
set_param(model, "Description", ['ETS2 truck ACC (MPC upper level, measured-map allocator, ' ...
    'Stateflow modes). Built by build_acc_controller.m; parameters acc_controller_params.m.']);
hws = get_param(model, "ModelWorkspace");
hws.DataSource = "MATLAB Code";
hws.MATLABCode = workspace_code(C);
hws.reload();
acc_codegen_config(model);
set_param(model, "InitFcn", "acc_controller_init;");   % MPC objects -> base workspace

% ---------------- root I/O (contract) ------------------------------------------------------
ins = {"enable", "boolean"; "set_speed_mps", "double"; "time_gap_s", "double";
       "ego_speed_mps", "double"; "ego_accel_mps2", "double"; "lead_valid", "boolean";
       "lead_gap_m", "double"; "lead_speed_mps", "double"; "lead_accel_mps2", "double";
       "resume", "boolean"; "engine_rpm", "double"; "gear", "int32"};
outs = {"throttle", "double"; "brake", "double"; "retarder_step", "int32";
        "engine_brake", "boolean"; "a_des_mps2", "double"; "mode", "uint8"};
for i = 1:size(ins, 1)
    add_block("simulink/Sources/In1", model + "/" + ins{i, 1}, "Port", num2str(i), ...
        "OutDataTypeStr", ins{i, 2}, "PortDimensions", "1", "SampleTime", "C.Ts", ...
        "Position", [40 40+45*i 70 54+45*i]);
end
for i = 1:size(outs, 1)
    add_block("simulink/Sinks/Out1", model + "/" + outs{i, 1}, "Port", num2str(i), ...
        "OutDataTypeStr", outs{i, 2}, "Position", [900 60+60*i 930 74+60*i]);
end
sub = model + "/ACC_Controller";
add_block("simulink/Ports & Subsystems/Subsystem", sub, "Position", [400 80 620 640]);
delete_line(sub, "In1/1", "Out1/1"); delete_block(sub + "/In1"); delete_block(sub + "/Out1");
set_param(sub, "TreatAsAtomicUnit", "on");
for i = 1:size(ins, 1)
    add_block("simulink/Sources/In1", sub + "/" + ins{i, 1}, "Port", num2str(i));
    add_line(model, ins{i, 1} + "/1", "ACC_Controller/" + i);
end
for i = 1:size(outs, 1)
    add_block("simulink/Sinks/Out1", sub + "/" + outs{i, 1}, "Port", num2str(i));
    add_line(model, "ACC_Controller/" + i, outs{i, 1} + "/1");
end
build_inside(sub, C);
Simulink.BlockDiagram.arrangeSystem(sub);
save_system(model, file);
end

% =====================================================================
function code = workspace_code(C)
lines = ["% Generated by build_acc_controller.m (edit acc_controller_params.m / acc_design_mpc.m)"
         "C = acc_controller_params();"
         "acc_controller_init();   % mpcComfort, mpcEmergency in the base workspace (MPC blocks read them there)"];
for f = string(fieldnames(C.mode)).'
    lines(end+1) = sprintf("MODE_%s = C.mode.%s;", f, f); %#ok<AGROW>
end
lines(end+1) = "MODE_dt = C.Ts;";
lines(end+1) = "FOL_d0 = C.fol.d0;";
lines(end+1) = "FOL_a_approach = C.fol.a_approach;";
code = strjoin(lines, newline);
end

function build_inside(sub, C)
rt = sfroot;
% ---------------- input conditioning ----------------
mfun(sub, "InputConditioning", strjoin([
"function [th, vset, v, a_f, lead_ok, gap, vl, al_eff, ttc, dreq] = InputConditioning(set_speed, time_gap, ego_speed, ego_accel, lead_valid, lead_gap, lead_speed, lead_accel, C)"
"[th, vset, v, a_f, lead_ok, gap, vl, al_eff, ttc, dreq] = acc_condition(set_speed, time_gap, ego_speed, ego_accel, lead_valid, lead_gap, lead_speed, lead_accel, C);"], newline), rt);
ln(sub, "set_speed_mps/1", "InputConditioning/1"); ln(sub, "time_gap_s/1", "InputConditioning/2");
ln(sub, "ego_speed_mps/1", "InputConditioning/3"); ln(sub, "ego_accel_mps2/1", "InputConditioning/4");
ln(sub, "lead_valid/1", "InputConditioning/5"); ln(sub, "lead_gap_m/1", "InputConditioning/6");
ln(sub, "lead_speed_mps/1", "InputConditioning/7"); ln(sub, "lead_accel_mps2/1", "InputConditioning/8");

% ---------------- mode logic ----------------
build_mode_chart(sub + "/ModeLogic", C);
% chart inputs: enable lead_ok gap v vl resume ttc dreq th
ln(sub, "enable/1", "ModeLogic/1"); ln(sub, "InputConditioning/5", "ModeLogic/2");
ln(sub, "InputConditioning/6", "ModeLogic/3"); ln(sub, "InputConditioning/3", "ModeLogic/4");
ln(sub, "InputConditioning/7", "ModeLogic/5"); ln(sub, "resume/1", "ModeLogic/6");
ln(sub, "InputConditioning/9", "ModeLogic/7"); ln(sub, "InputConditioning/10", "ModeLogic/8");
ln(sub, "InputConditioning/1", "ModeLogic/9");

% ---------------- MPC preparation ----------------
mfun(sub, "MPC_Prep", strjoin([
"function [x, ref, md, umin, umax, ymin, ymax, ywt, sw] = MPC_Prep(mode, v, a_f, gap, vl, al_eff, th, vset, mv_prev, C)"
"[x, ref, md, umin, umax, ymin, ymax, ywt, sw] = acc_mpc_prep(double(mode), v, a_f, gap, vl, al_eff, th, vset, mv_prev, C);"], newline), rt);
ln(sub, "ModeLogic/1", "MPC_Prep/1"); ln(sub, "InputConditioning/3", "MPC_Prep/2");
ln(sub, "InputConditioning/4", "MPC_Prep/3"); ln(sub, "InputConditioning/6", "MPC_Prep/4");
ln(sub, "InputConditioning/7", "MPC_Prep/5"); ln(sub, "InputConditioning/8", "MPC_Prep/6");
ln(sub, "InputConditioning/1", "MPC_Prep/7"); ln(sub, "InputConditioning/2", "MPC_Prep/8");

% ---------------- MPC ----------------
mpcb = sub + "/MPC";
add_block("mpclib/Multiple MPC Controllers", mpcb);
acc_controller_init();
set_param(mpcb, "mpcobjs", "{'mpcComfort','mpcEmergency'}", "x0s", "{[],[]}", "state_inport_multiple", "on", ...
    "md_inport_multiple", "on", "mv_inport_multiple", "on", "umin_inport_multiple", "on", ...
    "umax_inport_multiple", "on", "ymin_inport_multiple", "on", "ymax_inport_multiple", "on", ...
    "ywt_inport_multiple", "on", "return_mvseq_multiple", "on", "return_qpstatus_multiple", "on");
% ports: 1 switch 2 x 3 ref 4 md 5 ext.mv 6 umin 7 umax 8 ymin 9 ymax 10 y.wt
ln(sub, "MPC_Prep/9", "MPC/1"); ln(sub, "MPC_Prep/1", "MPC/2"); ln(sub, "MPC_Prep/2", "MPC/3");
ln(sub, "MPC_Prep/3", "MPC/4"); ln(sub, "MPC_Prep/4", "MPC/6"); ln(sub, "MPC_Prep/5", "MPC/7");
ln(sub, "MPC_Prep/6", "MPC/8"); ln(sub, "MPC_Prep/7", "MPC/9"); ln(sub, "MPC_Prep/8", "MPC/10");

mfun(sub, "MPC_Post", strjoin([
"function [mv_used, a_seq_mean] = MPC_Post(mv, mvseq, qp_status, mv_prev, C)"
"% QP failure (status < 0: infeasible or numerical): never accelerate, keep the last braking"
"if qp_status < 0"
"    mv_used = [min(mv_prev(1), 0); mv_prev(2)];"
"else"
"    mv_used = mv;"
"end"
"% mean of the predicted total request (drive + brake path) over C.alc.ret5_window"
"n = min(size(mvseq, 1), max(1, round(C.alc.ret5_window / C.Ts)));"
"a_seq_mean = sum(sum(mvseq(1:n, :))) / n;"], newline), rt);
ln(sub, "MPC/1", "MPC_Post/1"); ln(sub, "MPC/2", "MPC_Post/2"); ln(sub, "MPC/3", "MPC_Post/3");

% ---------------- allocator ----------------
mfun(sub, "Allocator", strjoin([
"function [throttle, brake, ret_step, engine_brake, a_des, mv_app] = Allocator(mode, mv, a_seq_mean, v, a_f, gear, rpm, dreq, C)"
"[throttle, brake, ret_step, engine_brake, a_des, mv_app] = acc_allocate(double(mode), mv, a_seq_mean, v, a_f, gear, rpm, dreq, C);"], newline), rt);
ln(sub, "ModeLogic/1", "Allocator/1"); ln(sub, "MPC_Post/1", "Allocator/2"); ln(sub, "MPC_Post/2", "Allocator/3");
ln(sub, "InputConditioning/3", "Allocator/4"); ln(sub, "InputConditioning/4", "Allocator/5");
ln(sub, "gear/1", "Allocator/6"); ln(sub, "engine_rpm/1", "Allocator/7"); ln(sub, "InputConditioning/10", "Allocator/8");
add_block("simulink/Discrete/Unit Delay", sub + "/mv_last", "SampleTime", "C.Ts", "InitialCondition", "[0; 0]");
ln(sub, "Allocator/6", "mv_last/1"); ln(sub, "mv_last/1", "MPC/5"); ln(sub, "mv_last/1", "MPC_Prep/9"); ln(sub, "mv_last/1", "MPC_Post/4");

% ---------------- outputs ----------------
add_block("simulink/Signal Attributes/Data Type Conversion", sub + "/ret_int", "OutDataTypeStr", "int32");
add_block("simulink/Signal Attributes/Data Type Conversion", sub + "/eb_bool", "OutDataTypeStr", "boolean");
ln(sub, "Allocator/1", "throttle/1"); ln(sub, "Allocator/2", "brake/1");
ln(sub, "Allocator/3", "ret_int/1"); ln(sub, "ret_int/1", "retarder_step/1");
ln(sub, "Allocator/4", "eb_bool/1"); ln(sub, "eb_bool/1", "engine_brake/1");
ln(sub, "Allocator/5", "a_des_mps2/1"); ln(sub, "ModeLogic/1", "mode/1");
end

function mfun(sub, name, script, rt)
path = sub + "/" + name;
add_block("simulink/User-Defined Functions/MATLAB Function", path);
ch = rt.find("-isa", "Stateflow.EMChart", "Path", char(path));
ch.Script = char(script);
d = ch.find("-isa", "Stateflow.Data", "Name", "C");
d.Scope = "Parameter";
d.Props.Complexity = "Off";
d.Tunable = false;
end

function build_mode_chart(path, C)
add_block("sflib/Chart", path);
rt = sfroot;
ch = rt.find("-isa", "Stateflow.Chart", "Path", char(path));
ch.ActionLanguage = "MATLAB";
ch.ChartUpdate = "DISCRETE";
ch.SampleTime = num2str(C.Ts);
ch.Description = ['ACC modes: 0 OFF, 1 CRUISE, 2 FOLLOW, 3 STOP, 4 HOLD, 5 GO, 6 EMERGENCY. ' ...
    'enable false -> OFF. FOLLOW when a lead is within the follow range; STOP when the lead has ' ...
    'stopped; HOLD at standstill (brake held); GO automatically when the lead pulls away by more ' ...
    'than MODE_go_gap within MODE_go_window s of stopping, otherwise on resume; EMERGENCY when ' ...
    'TTC < MODE_ttc_on or the required deceleration > MODE_dreq_on.'];
in = ["enable", "lead_ok", "gap", "v", "vl", "resume", "ttc", "dreq", "th"];
for i = 1:numel(in), d = sfdata(ch, in(i), "Input"); d.Props.Array.Size = "1"; end
o = sfdata(ch, "mode", "Output"); o.DataType = "uint8"; o.Props.InitialValue = "0";
sfdata(ch, "t_hold", "Local", "99");
sfdata(ch, "gap_stop", "Local", "0");
for f = string(fieldnames(C.mode)).'
    sfdata(ch, "MODE_" + f, "Parameter");
end
sfdata(ch, "MODE_dt", "Parameter"); sfdata(ch, "FOL_d0", "Parameter"); sfdata(ch, "FOL_a_approach", "Parameter");

sOFF = sfstate(ch, ["OFF", "entry: mode = uint8(0);"], [30 30 140 70]);
sON = sfstate(ch, "ON", [230 30 900 620]);
sC = sfstate(sON, ["CRUISE", "entry: mode = uint8(1);"], [300 90 150 60]);
sF = sfstate(sON, ["FOLLOW", "entry: mode = uint8(2);"], [560 90 150 60]);
sS = sfstate(sON, ["STOP", "entry: mode = uint8(3);"], [820 90 150 60]);
sH = sfstate(sON, ["HOLD", "entry: mode = uint8(4);", "during: t_hold = t_hold + MODE_dt;"], [820 300 200 80]);
sG = sfstate(sON, ["GO", "entry: mode = uint8(5);"], [560 300 150 60]);
sE = sfstate(sON, ["EMERGENCY", "entry: mode = uint8(6);"], [300 450 170 60]);

t = Stateflow.Transition(ch); t.Destination = sOFF; t.SourceEndpoint = [60 10]; t.MidPoint = [60 20];
sftrans(ch, sOFF, sON, "[enable]", 1);
sftrans(ch, sON, sOFF, "[~enable]", 1);
% default entry into ON
j = Stateflow.Junction(sON); j.Position.Center = [260 200]; j.Position.Radius = 7;
t = Stateflow.Transition(sON); t.Destination = j; t.SourceEndpoint = [260 160]; t.MidPoint = [260 180];
sftrans(sON, j, sH, "[v < MODE_v_standstill]{t_hold = 99; gap_stop = gap;}", 1);
sftrans(sON, j, sF, "[lead_ok && gap < follow_range()]", 2);
sftrans(sON, j, sC, "", 3);

emerg = "[lead_ok && (ttc < MODE_ttc_on || dreq > MODE_dreq_on)]";
sftrans(sON, sC, sE, emerg, 1);
sftrans(sON, sC, sF, "[lead_ok && gap < follow_range()]", 2);
sftrans(sON, sF, sE, emerg, 1);
sftrans(sON, sF, sS, "[lead_ok && vl < MODE_v_lead_stopped]", 2);
sftrans(sON, sF, sC, "[duration(~lead_ok) > MODE_lead_lost_s || (lead_ok && gap > follow_range() + MODE_follow_hyst)]", 3);
sftrans(sON, sS, sE, emerg, 1);
sftrans(sON, sS, sH, "[v < MODE_v_standstill]{t_hold = 0; gap_stop = gap;}", 2);
sftrans(sON, sS, sF, "[lead_ok && vl > MODE_v_lead_moving]", 3);
sftrans(sON, sS, sC, "[duration(~lead_ok) > MODE_lead_lost_s]", 4);
sftrans(sON, sH, sG, "[resume || (t_hold <= MODE_go_window && lead_ok && gap > gap_stop + MODE_go_gap)]", 1);
sftrans(sON, sG, sE, emerg, 1);
sftrans(sON, sG, sS, "[lead_ok && vl < MODE_v_lead_stopped && v < MODE_v_lead_moving]", 2);
sftrans(sON, sG, sF, "[v > MODE_go_done_v && lead_ok]", 3);
sftrans(sON, sG, sC, "[v > MODE_go_done_v && ~lead_ok]", 4);
sftrans(sON, sE, sH, "[v < MODE_v_standstill]{t_hold = 0; gap_stop = gap;}", 1);
sftrans(sON, sE, sF, "[lead_ok && duration(ttc > MODE_ttc_off && dreq < MODE_dreq_off) > MODE_emerg_hold]", 2);
sftrans(sON, sE, sC, "[duration(~lead_ok) > MODE_emerg_hold]", 3);

f = Stateflow.EMFunction(ch);
f.LabelString = "r = follow_range()";
f.Position = [30 700 200 60];
f.Script = char(strjoin([
"function r = follow_range()"
"% distance within which a lead matters: target gap + distance to settle at a_approach + margin"
"r = FOL_d0 + th*v + max(v - vl, 0)^2/(2*FOL_a_approach) + MODE_follow_range_extra;"], newline));
end

function d = sfdata(ch, name, scope, init)
d = Stateflow.Data(ch);
d.Name = char(name);
d.Scope = char(scope);
if nargin > 3, d.Props.InitialValue = char(init); end
end

function s = sfstate(parent, lines, pos)
s = Stateflow.State(parent);
s.LabelString = char(strjoin(lines, newline));
s.Position = pos;
end

function t = sftrans(parent, src, dst, label, order)
t = Stateflow.Transition(parent);
t.Source = src; t.Destination = dst;
t.LabelString = char(label);
t.ExecutionOrder = order;
% straight line between the two centres keeps the transition inside its parent state
t.MidPoint = (centre(src) + centre(dst)) / 2;
end

function c = centre(o)
if isa(o, "Stateflow.Junction")
    c = o.Position.Center;
else
    c = o.Position(1:2) + o.Position(3:4) / 2;
end
end

function ln(sys, from, to)
add_line(sys, from, to, "autorouting", "smart");
end
